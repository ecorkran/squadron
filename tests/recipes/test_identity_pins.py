@pytest.fixture(autouse=True)
def built_in_aliases_only(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(aliases, "load_user_aliases", lambda: {})


def _recipe_path(name: str) -> Path:
    directory = shipped_recipes_dir() if name in SHIPPED_NAMES else REFERENCE_DIR
    return directory / f"{name}.yaml"


@pytest.mark.parametrize("name", sorted(PINS))
def test_recipe_hash_is_unchanged(name: str) -> None:
    assert recipe_hash(load_recipe(_recipe_path(name))) == PINS[name][0]


@pytest.mark.parametrize("name", sorted(PINS))
def test_stage_config_keys_are_unchanged(name: str) -> None:
    recipe = load_recipe(_recipe_path(name))
    keys = [config.config_key for config in planned_stages(recipe, REVIEW_TEMPLATE_HASH)]
    assert keys == PINS[name][1]
